def keyword_fallback_video_key(question: str) -> str | None:
    """LLM video_key таңдамай қалса іске қосылатын сақтандырғыш тексеру.

    "fallback_keywords" бойынша ЕҢ ҰЗЫН (яғни ең нақты/спецификалық) сәйкес
    келген сөз/тіркес жеңеді — тақырыптардың бірінің тіркесі екінші
    тақырыптың тіркесінің ІШІНДЕ жатса (мыс. "зачем учить python" деген
    қысқа тіркес "зачем учить python если есть chatgpt" деген ұзынырақ, басқа
    тақырыпқа тиесілі тіркестің ішінде кездеседі), дұрысы — неғұрлым нақтысы,
    сөздіктегі реті емес. Ешбір "fallback_keywords" сәйкес келмесе, барып
    "fallback_subject_words" + "fallback_intent_words" комбинациясы
    (әр топтан кемінде бір сөз бірге кездессе) тексеріледі.
    """
    normalized = question.lower()

    best_key: str | None = None
    best_len = -1
    for key, meta in VIDEO_LIBRARY.items():
        for word in meta.get("fallback_keywords", ()):
            if word in normalized and len(word) > best_len:
                best_key = key
                best_len = len(word)
    if best_key is not None:
        return best_key

    for key, meta in VIDEO_LIBRARY.items():
        subject_words = meta.get("fallback_subject_words", ())
        intent_words = meta.get("fallback_intent_words", ())
        if subject_words and intent_words:
            has_subject = any(word in normalized for word in subject_words)
            has_intent = any(word in normalized for word in intent_words)
            if has_subject and has_intent:
                return key

    return None


def validate_video_files() -> None:
    """Каталогтағы video_key-лерге сәйкес файлдар шынымен бар-жоғын тексереді.

    Сервер іске қосылғанда шақырылады (backend/main.py lifespan) — жаңа
    жазба қосылып, файл әлі көшірілмеген жағдайда ескерту логқа шығады.
    """
    for key, meta in VIDEO_LIBRARY.items():
        url = meta.get("url", "")
        if not url.startswith("/static/"):
            continue
        file_path = STATIC_DIR / url.removeprefix("/static/")
        if not file_path.is_file():
            logger.warning(
                "video_key=%s үшін файл табылмады: %s (VIDEO_LIBRARY-де "
                "жазба бар, бірақ static/videos/ ішінде файл жоқ)",
                key, file_path,
            )
